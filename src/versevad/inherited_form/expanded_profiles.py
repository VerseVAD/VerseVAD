"""Expanded, source-documented inherited-form profile catalog.

The registry intentionally distinguishes automatic, partial, and manual
assessment.  A manual profile remains inspectable with its requirements and
weights, but it can never become an automatic VerseVAD suggestion.
"""

from __future__ import annotations

from typing import Any, Callable


