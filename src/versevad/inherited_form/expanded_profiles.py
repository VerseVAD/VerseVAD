    def fixed(
        profile_id: str,
        name: str,
        family: str,
        tradition: str,
        definition: str,
        *,
        source_urls: tuple[str, ...] = (POETS_GLOSSARY,),
        line_count: int | tuple[int, int] | None = None,
        stanza_patterns: tuple[tuple[int, ...], ...] = (),
        rhyme_schemes: tuple[str, ...] = (),
        syllables: tuple[int, ...] = (),
        repeating_syllables: tuple[int, ...] = (),
        syllable_range: tuple[int, int] | None = None,
        word_counts: tuple[int, ...] = (),
        meter: tuple[str, int] | None = None,
        extra_rules: tuple[Any, ...] = (),
        limitations: tuple[str, ...] = (),
        assessment_mode: str = "automatic",
    ) -> Any:
        rules: list[Any] = []
        if isinstance(line_count, int):
            rules.append(
                rule(
                    "lines",
                    "line_count_exact",
                    "Line count",
                    role.REQUIRED,
                    5,
                    f"{line_count} lines",
                    count=line_count,
                )
            )
        elif line_count is not None:
            minimum, maximum = line_count
            rules.append(
                rule(
                    "lines",
                    "line_count_range",
                    "Line-count range",
                    role.REQUIRED,
                    4,
                    f"{minimum}-{maximum} lines",
                    minimum=minimum,
                    maximum=maximum,
                )
            )
        if stanza_patterns:
            rules.append(
                rule(
                    "stanzas",
                    "stanza_pattern",
                    "Stanza architecture",
                    role.REQUIRED,
                    4,
                    " or ".join("/".join(map(str, item)) for item in stanza_patterns),
                    patterns=stanza_patterns,
                )
            )
        if rhyme_schemes:
            rules.append(
                rule(
                    "rhyme",
                    "rhyme_scheme",
                    "Rhyme architecture",
                    role.REQUIRED,
                    5,
                    " or ".join(rhyme_schemes),
                    schemes=rhyme_schemes,
                )
            )
        if syllables:
            rules.append(
                rule(
                    "syllables",
                    "syllable_pattern",
                    "Syllable pattern",
                    role.REQUIRED,
                    5,
                    "/".join(map(str, syllables)),
                    counts=syllables,
                )
            )
        if repeating_syllables:
            rules.append(
                rule(
                    "syllables",
                    "syllable_pattern_repeating",
                    "Repeating syllable pattern",
                    role.PREFERRED,
                    4,
                    "/".join(map(str, repeating_syllables)) + " repeating",
                    counts=repeating_syllables,
                )
            )
        if syllable_range is not None:
            minimum, maximum = syllable_range
            rules.append(
                rule(
                    "syllable_range",
                    "syllable_range",
                    "Line syllable range",
                    role.PREFERRED,
                    3,
                    f"{minimum}-{maximum} syllables per line",
                    minimum=minimum,
                    maximum=maximum,
                )
            )
        if word_counts:
            rules.append(
                rule(
                    "word_counts",
                    "word_count_pattern",
                    "Words per line",
                    role.REQUIRED,
                    5,
                    "/".join(map(str, word_counts)),
                    counts=word_counts,
                )
            )
        if meter is not None:
            pattern, foot_count = meter
            rules.append(
                rule(
                    "meter",
                    "meter_pattern",
                    "Governing meter",
                    role.PREFERRED,
                    4,
                    f"{pattern} meter with {foot_count} feet",
                    pattern=pattern,
                    foot_count=foot_count,
                )
            )
        rules.extend(extra_rules)
        tooltip = f"Traditionally: {definition[0].lower() + definition[1:]}"
        return form_profile(
            profile_id=profile_id,
            name=name,
            family=family,
            tradition=tradition,
            definition=definition,
            tooltip_definition=tooltip,
            rules=tuple(rules),
            source_urls=source_urls,
            limitations=limitations,
            assessment_mode=assessment_mode,
        )

